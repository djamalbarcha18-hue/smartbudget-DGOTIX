// Writes the privacy policy and terms as static pages for the DGOTIX website
// (privacy.html, terms.html), from the same text the app shows
// (lib/features/legal/domain/legal_content.dart), so the two never differ.
//
//   dart run tool/export_legal.dart <website folder>
import 'dart:io';

import 'package:smartbudget/core/config/app_config.dart';
import 'package:smartbudget/features/legal/domain/legal_content.dart';

String _esc(String s) => s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');

/// Turns the support email in [s] into a mailto link (after escaping).
String _body(String s) {
  final String e = _esc(s);
  const String mail = AppConfig.supportEmail;
  return mail.isEmpty
      ? e
      : e.replaceAll(mail, '<a href="mailto:$mail">$mail</a>');
}

String _article(LegalDoc doc, {required bool ar}) {
  final String title = switch (doc) {
    LegalDoc.privacy => ar ? 'سياسة الخصوصية' : 'Privacy Policy',
    LegalDoc.terms => ar ? 'شروط الاستخدام' : 'Terms of Use',
  };
  final String updated = ar
      ? 'آخر تحديث: ${LegalContent.lastUpdated}'
      : 'Last updated: ${LegalContent.lastUpdated}';
  final StringBuffer b = StringBuffer()
    ..writeln(ar ? '  <article>' : '  <article id="en" lang="en" dir="ltr">')
    ..writeln('    <h1>$title — ${AppConfig.appName}</h1>')
    ..writeln('    <p class="meta">$updated</p>');
  for (final LegalSection s in LegalContent.sections(doc, ar: ar)) {
    b
      ..writeln('    <h2>${_esc(s.heading)}</h2>')
      ..writeln('    <p>${_body(s.body)}</p>');
  }
  final String links = ar
      ? '<a href="terms.html">شروط الاستخدام</a> · '
          '<a href="privacy.html">سياسة الخصوصية</a> · '
          '<a href="refund.html">سياسة الاسترجاع</a>'
      : '<a href="terms.html#en">Terms of use</a> · '
          '<a href="privacy.html#en">Privacy policy</a> · '
          '<a href="refund.html#en">Refund policy</a>';
  b
    ..writeln('    <p class="meta" style="margin-top:20px">$links</p>')
    ..writeln('  </article>');
  return b.toString();
}

String _page(LegalDoc doc, String file) {
  final String title = switch (doc) {
    LegalDoc.privacy => 'سياسة الخصوصية · Privacy Policy',
    LegalDoc.terms => 'شروط الاستخدام · Terms of Use',
  };
  return '''<!doctype html>
<!-- Generated by tool/export_legal.dart in the SmartBudget app repository;
     edit lib/features/legal/domain/legal_content.dart there, not this file. -->
<html lang="ar" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'none'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; object-src 'none'; base-uri 'self'; form-action 'none'; upgrade-insecure-requests">
<meta name="referrer" content="strict-origin-when-cross-origin">
<title>$title — ${AppConfig.appName}</title>
<link rel="canonical" href="https://dgotix.com/$file">
<link rel="icon" type="image/png" href="smartbudget-icon.png">
<link rel="stylesheet" href="legal.css">
</head>
<body>
<div class="wrap">
  <header>
    <a href="/"><img src="logo.svg" alt="DGOTIX"></a>
    <a href="#en">English</a>
  </header>

${_article(doc, ar: true)}
${_article(doc, ar: false)}
  <footer><span dir="ltr">© ${DateTime.now().year} DGOTIX</span></footer>
</div>
</body>
</html>
''';
}

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/export_legal.dart <website folder>');
    exit(64);
  }
  final Directory out = Directory(args.first);
  File('${out.path}/privacy.html')
      .writeAsStringSync(_page(LegalDoc.privacy, 'privacy.html'));
  File('${out.path}/terms.html')
      .writeAsStringSync(_page(LegalDoc.terms, 'terms.html'));
  stdout.writeln('Wrote privacy.html and terms.html to ${out.path}');
}
